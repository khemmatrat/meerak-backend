function hasAny(text, patterns) {
  const t = String(text || '').toLowerCase();
  return patterns.some((p) => p.test(t));
}

function insuranceClaimAnswer() {
  return `ได้ครับ ถ้าต้องการใช้ “ประกันงาน / เคลมประกัน” ให้ทำตามนี้ได้เลย:

1. เข้าไปที่หน้า **รายละเอียดงาน** ของงานนั้น
2. ตรวจว่างานนั้นมีสถานะว่า **มีประกันคุ้มครอง** หรือมีใบการันตีประกันงาน
3. ถ้างานมีปัญหา ให้กด **รายงานปัญหา** หรือในส่วนประกันให้กด **ยื่นเคลมประกัน**
4. กรอกรายละเอียดเหตุการณ์ให้ชัดเจน เช่น ผู้รับงานไม่มา, งานไม่เสร็จ, งานไม่ตรงตามที่ตกลง หรือมีเหตุฉุกเฉิน
5. กด **ยืนยันเคลม** แล้วรอทีมงานพิจารณา โดยปกติใช้เวลาประมาณ **24–48 ชั่วโมง**

เงื่อนไขสำคัญ:
• ต้องเป็นผู้จ้างงาน/เจ้าของงานนั้น
• งานต้องมีประกันที่ซื้อไว้หรือมีสถานะคุ้มครอง
• เคลมได้ 1 ครั้งต่องาน
• ประกันครอบคลุมการจัดหาผู้รับงานใหม่ในวงเงิน 40% ของวงเงินประกัน ส่วน 60% ถูกสำรองไว้เพื่อความมั่นคงของแพลตฟอร์ม

ถ้าไม่เห็นปุ่ม **ยื่นเคลมประกัน** ให้ตรวจว่าเข้าด้วยบัญชีเจ้าของงาน, งานนั้นซื้อประกันไว้แล้ว, และงานอยู่ในสถานะที่สามารถรายงานปัญหา/Dispute ได้ครับ`;
}

function insuranceBuyAnswer() {
  return `ได้ครับ วิธีเปิดใช้ประกันงานคือ:

1. เข้าไปที่หน้า **รายละเอียดงาน** ก่อนผู้รับงานรับงาน หรือก่อนขั้นตอนชำระเงิน
2. เปิดตัวเลือก **Premium Protect / ประกันงาน / มีใบการันตีประกันงาน**
3. ระบบจะแสดงค่าเบี้ยประกันตามหมวดงาน เช่นเป็นเปอร์เซ็นต์ของค่าจ้าง
4. เมื่อชำระเงินหรืออนุมัติงาน ระบบจะรวมค่าประกันไว้ในยอดที่ต้องจ่าย และงานจะมีสถานะ **มีประกันคุ้มครอง**

หลังซื้อแล้ว หากงานมีปัญหา คุณสามารถกลับมาที่หน้าเดิมและกด **ยื่นเคลมประกัน** ได้ครับ`;
}

function suddenOwnerCancelAnswer() {
  return `เข้าใจครับ กรณีต้องยกเลิกงานแบบกระทันหันหลังมีผู้รับงานรับแล้ว โดยเฉพาะใกล้เวลาเริ่มงานหรือผู้รับงานกำลังเดินทาง ระบบต้องดูแลทั้งสองฝ่ายให้เร็วที่สุด:

สิ่งที่ผู้จ้างควรทำทันที:
1. เข้าไปที่หน้า **รายละเอียดงาน**
2. กด **ยกเลิกงาน** ถ้าปุ่มยังเปิดให้กดได้
3. ถ้าเป็นงานเดินทาง/งานที่ผู้รับงานเริ่มเดินทางแล้ว ระบบอาจแสดง **ค่าธรรมเนียมยกเลิก** หรือเงินชดเชยให้ผู้รับงานก่อนยืนยัน
4. ถ้ายังต้องการบริการอยู่ ให้ติดต่อ support ทันทีและระบุว่า **ต้องการจับคู่ผู้รับงานใหม่ด่วน**
5. ส่งข้อมูลสำคัญให้ครบ: เวลาที่ต้องเริ่มงาน, สถานที่, ประเภทงาน, และเหตุผลที่ต้องยกเลิก/เปลี่ยนคน

แนวทางที่ระบบจะช่วย:
• ถ้างานยังแก้ไขได้ ระบบจะพยายามเปิดเคสด่วนเพื่อหาผู้รับงานที่ว่างหรือเหมาะสมกว่า
• ถ้าเป็นงานที่มีประกัน/เหตุฉุกเฉิน ทีมจะใช้ข้อมูลนั้นช่วยพิจารณาการจัดหาคนแทน
• ถ้ามีค่าธรรมเนียมหรือเงินชดเชย ระบบจะแจ้งก่อนยืนยันเพื่อความเป็นธรรมกับผู้รับงานที่กำลังเดินทาง

เพื่อไม่ให้ลูกค้าถูกทิ้งกลางทาง แนะนำให้พิมพ์ต่อว่า “ต้องการจับคู่ใหม่ด่วน” พร้อมเวลาที่ต้องเริ่มงาน ระบบจะส่งเคสให้ทีมจัดการแบบเร่งด่วนครับ`;
}

function providerCancelNotWorthAnswer() {
  return `กรณีผู้รับงานรับงานแล้ว แต่ภายหลังประเมินว่าไม่คุ้มหรือรับเงื่อนไขบางจุดไม่ได้ ไม่ควรปล่อยให้ลูกค้ารอโดยไม่มีทางออกครับ

สิ่งที่ผู้รับงานควรทำทันที:
1. แจ้งเหตุผลตรงไปตรงมาในแชทงานหรือ support เช่น ระยะทางไกลกว่าที่คาด, ค่าใช้จ่ายไม่คุ้ม, เงื่อนไขหน้างานไม่ตรงที่เข้าใจ
2. อย่าหายไปเฉย ๆ เพราะจะกระทบคะแนนความน่าเชื่อถือและประสบการณ์ลูกค้า
3. ถ้ายังไม่เริ่มเดินทาง ให้รีบแจ้งเพื่อให้ระบบมีเวลาหาคนใหม่
4. ถ้าเริ่มเดินทางแล้วแต่ทำไม่ได้ ให้แจ้งสถานะล่าสุดและตำแหน่ง/เวลาที่คาดว่าจะไปต่อไม่ได้

แนวทางที่ระบบควรช่วยลูกค้าทันที:
• เปิดเคสด่วนเพื่อหาผู้รับงานใหม่ที่ว่างอยู่
• ให้ลูกค้าระบุว่า “ยังต้องการบริการเดิม” หรือ “ต้องการยกเลิก/คืนเงินตามเงื่อนไข”
• เก็บเหตุผลของผู้รับงานไว้ในเคส เพื่อให้ทีมตรวจสอบความเป็นธรรมและปรับปรุงการจับคู่ครั้งต่อไป

ถ้าคุณเป็นลูกค้า ให้พิมพ์ “ต้องการหาคนใหม่ด่วน” พร้อมเวลาที่ต้องการเริ่มงาน ระบบจะช่วยดันเคสนี้เป็น priority สูงครับ`;
}

function providerEmergencyAnswer() {
  return `รับทราบครับ กรณีผู้รับงานแจ้งอุบัติเหตุ เจ็บป่วย รถเสีย ภัยธรรมชาติ หรือเหตุสุดวิสัย ระบบต้องให้ความสำคัญกับเวลาและความปลอดภัยก่อน

สิ่งที่ระบบรองรับ:
• ผู้รับงานสามารถรายงานเหตุฉุกเฉิน เช่น อุบัติเหตุ, เจ็บป่วยกะทันหัน, รถเสีย/ปัญหาเดินทาง, เหตุฉุกเฉินครอบครัว, ภัยธรรมชาติ หรือเหตุสุดวิสัย
• เมื่อรายงานแล้ว งานจะถูกตั้งเป็นสถานะรอตรวจเหตุฉุกเฉิน และระบบจะแจ้งลูกค้าว่าผู้รับงานแจ้งเหตุอะไร
• ระบบจะเปิดเคสด่วนให้ทีมช่วยหาผู้รับงานใหม่หรือแนวทางชดเชย/คืนเงินตามสถานการณ์
• ในบางกรณีระบบอาจสร้างคูปองขออภัยให้ลูกค้าอัตโนมัติ

สิ่งที่ลูกค้าควรทำตอนนี้:
1. อยู่ในหน้า **รายละเอียดงาน** และเปิด support chat นี้ไว้
2. พิมพ์ว่า **ต้องการจับคู่ใหม่ด่วน** ถ้ายังต้องการบริการวันนี้
3. ระบุเวลาที่รับได้ล่าสุด เช่น “ต้องเริ่มภายใน 30 นาที”
4. ถ้ามีประกันงาน ให้แจ้งว่า “ขอใช้สิทธิประกัน/หาคนแทน”

สิ่งที่ผู้รับงานควรทำ:
• แจ้งเหตุให้ชัด เช่น อุบัติเหตุ/รถเสีย/เจ็บป่วย พร้อมหลักฐานถ้ามี
• ห้ามปล่อยงานเงียบ ๆ เพราะระบบต้องใช้ข้อมูลนี้เพื่อปกป้องทั้งลูกค้าและผู้รับงาน

หลักคิดของระบบคือไม่ทิ้งลูกค้าไว้กลางทาง และไม่บังคับผู้รับงานให้ทำงานเมื่อไม่ปลอดภัยครับ`;
}

function resolveSystemSupportKnowledge(userText) {
  const text = String(userText || '');
  const urgentJobProblem = hasAny(text, [
    /ยกเลิก.*กระทันหัน/,
    /กะทันหัน/,
    /ยกเลิก.*ก่อน.*เริ่ม/,
    /ใกล้.*เริ่ม/,
    /ใกล้.*ถึง/,
    /ผู้รับงาน.*ยกเลิก/,
    /คนรับงาน.*ยกเลิก/,
    /จับคู่ใหม่/,
    /หาคนใหม่/,
    /ไม่คุ้ม/,
    /ไม่คุ้มค่า/,
    /รับเงื่อนไข.*ไม่ได้/,
    /อุบัติเหตุ/,
    /สุดวิสัย/,
    /ฉุกเฉิน/,
    /รถเสีย/,
    /เจ็บป่วย/,
  ]);
  if (urgentJobProblem) {
    const providerEmergency = hasAny(text, [/อุบัติเหตุ/, /สุดวิสัย/, /ฉุกเฉิน/, /รถเสีย/, /เจ็บป่วย/, /ภัยธรรมชาติ/]);
    const providerCancels = hasAny(text, [/ผู้รับงาน.*ยกเลิก/, /คนรับงาน.*ยกเลิก/, /ไม่คุ้ม/, /ไม่คุ้มค่า/, /รับเงื่อนไข.*ไม่ได้/]);
    const answer = providerEmergency
      ? providerEmergencyAnswer()
      : providerCancels
        ? providerCancelNotWorthAnswer()
        : suddenOwnerCancelAnswer();
    return {
      key: providerEmergency ? 'provider_emergency_reroute' : providerCancels ? 'provider_cancel_reroute' : 'sudden_owner_cancel_reroute',
      question: providerEmergency
        ? 'ผู้รับงานแจ้งอุบัติเหตุหรือเหตุสุดวิสัย ต้องแก้ปัญหาอย่างไร'
        : providerCancels
          ? 'ผู้รับงานยกเลิกงานหรือรับเงื่อนไขไม่ได้ ต้องทำอย่างไร'
          : 'งานถูกยกเลิกกระทันหันก่อนเริ่มงานหรือใกล้ถึงเวลา ต้องทำอย่างไร',
      answer,
      category: 'urgent_job_reroute',
      confidence: 0.94,
      source: 'system_knowledge',
      actions: ['answered_from_system_knowledge', 'urgent_reroute_guidance', 'auto_save_safe_knowledge'],
      diagnosticSummary: 'ตอบจาก System Knowledge: cancel endpoint, incident report, nearby replacement worker/admin reroute, emergency handling',
    };
  }

  const wantsInsurance = hasAny(text, [
    /ประกันงาน/,
    /ประกัน/,
    /insurance/,
    /premium protect/,
    /คุ้มครอง/,
    /ใบการันตี/,
    /เคลม/,
    /claim/,
  ]);
  if (!wantsInsurance) return null;

  const wantsClaim = hasAny(text, [
    /เคลม/,
    /claim/,
    /แก้/,
    /ใช.*สิทธิ/,
    /งานมีปัญหา/,
    /ผู้รับงานไม่มา/,
    /ไม่เสร็จ/,
    /dispute/,
    /รายงานปัญหา/,
  ]);

  const answer = wantsClaim ? insuranceClaimAnswer() : insuranceBuyAnswer();
  return {
    key: wantsClaim ? 'insurance_claim_how_to' : 'insurance_buy_how_to',
    question: wantsClaim ? 'ประกันงานหรือเคลมประกันต้องทำอย่างไร' : 'วิธีเปิดใช้ประกันงานทำอย่างไร',
    answer,
    category: 'insurance',
    confidence: 0.92,
    source: 'system_knowledge',
    actions: ['answered_from_system_knowledge', 'auto_save_safe_knowledge'],
    diagnosticSummary: wantsClaim
      ? 'ตอบจาก System Knowledge: JobDetails มี flow ยื่นเคลมประกัน, เงื่อนไขเจ้าของงาน, 24–48 ชม., 40/60 policy'
      : 'ตอบจาก System Knowledge: JobDetails/Payment มี flow เปิด Premium Protect ก่อนชำระเงิน',
  };
}

export { resolveSystemSupportKnowledge };
