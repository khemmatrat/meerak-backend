interface LanguageContextType {
  language: Language;
  setLanguage: (lang: Language) => void;
  t: (key: string) => string;
}

const LanguageContext = createContext<LanguageContextType | undefined>(
  undefined,
);

const LANG_STORAGE_KEY = "aqond_lang";

export const LanguageProvider = ({ children }: { children?: ReactNode }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    if (typeof window !== "undefined") {
      const stored = localStorage.getItem(LANG_STORAGE_KEY) as Language | null;
      if (stored && ["en", "th", "zh", "ja", "fr", "ru"].includes(stored))
        return stored;
    }
    return "en";
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    if (typeof window !== "undefined") {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    }
  };

  const t = (path: string) => {
    const keys = path.split(".");

    // Helper to traverse object
    const getVal = (obj: any, keys: string[]) => {
      let current = obj;
      for (const key of keys) {
        if (current === undefined || current === null) return undefined;
        current = current[key];
      }
      return current;
    };

    let value = getVal(translations[language], keys);

    // Fallback to English if translation is missing
    if (value === undefined) {
      value = getVal(translations["en"], keys);
    }

    // Return path if both fail
    return typeof value === "string" ? value : path;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (context === undefined) {
    throw new Error("useLanguage must be used within a LanguageProvider");
  }
  return context;
};
